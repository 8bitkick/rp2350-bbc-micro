#!/usr/bin/env python3
"""embed_web.py <index.html> <out.c>: the web control panel's page, gzipped, as a C array in flash.
Fonts it refers to as url(fonts/<file>) are inlined as data URIs, so the page stands alone."""
import base64
import gzip
import os
import re
import sys

src, out = sys.argv[1], sys.argv[2]
page = open(src, 'rb').read()
webdiag = any(arg.lower() in ('--webdiag=on', '--webdiag=true', '--webdiag=1') for arg in sys.argv[3:])
page = page.replace(b'const WEBDIAG = true;', b'const WEBDIAG = ' + (b'true' if webdiag else b'false') + b';')

def inline(m):
    name = m.group(1).decode()
    font = open(os.path.join(os.path.dirname(src), 'fonts', name), 'rb').read()
    kind = 'font/otf' if name.endswith('.otf') else 'font/woff2'
    return b'url(data:' + kind.encode() + b';base64,' + base64.b64encode(font) + b')'

page = re.sub(rb'url\(fonts/([A-Za-z0-9_.-]+)\)', inline, page)
data = gzip.compress(page, compresslevel=9, mtime=0)
with open(out, 'w') as f:
    f.write('// generated by tools/embed_web.py from %s\n#include <stdint.h>\n' % src.split('/')[-1])
    f.write('const uint32_t presto_web_page_len = %d;\n' % len(data))
    f.write('const uint8_t presto_web_page[] __attribute__((aligned(4))) = {\n')
    for i in range(0, len(data), 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
